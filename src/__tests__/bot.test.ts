import { createBot } from "../bot";
import { websitePairing } from "../pairing/runtime";
import { registerCommands } from "../handlers/commands";
import { registerCallbacks } from "../handlers/callbacks";
import { registerAdmin } from "../handlers/admin";
import { handleText } from "../handlers/text";
import { setTelegramForCommands } from "../botCommands";
import { Telegraf } from "telegraf";
import { initContent } from "../content/loader";
jest.mock("../config/env", () => ({ env: { BOT_TOKEN: "999:synthetic-token" } }));
jest.mock("../content/loader", () => ({ initContent: jest.fn() }));
jest.mock("../handlers/commands", () => ({ registerCommands: jest.fn() }));
jest.mock("../handlers/callbacks", () => ({ registerCallbacks: jest.fn() }));
jest.mock("../handlers/admin", () => ({ registerAdmin: jest.fn() }));
jest.mock("../handlers/text", () => ({ handleText: jest.fn() }));
jest.mock("../botCommands", () => ({ setTelegramForCommands: jest.fn() }));
jest.mock("../pairing/runtime", () => ({ websitePairing: jest.fn() }));
jest.mock("telegraf", () => ({ Telegraf: jest.fn() }));
it("registers pairing before ordinary commands/text and redacts default update errors", async () => {
  const bot = { telegram: {}, catch: jest.fn(), use: jest.fn(), on: jest.fn() };
  (Telegraf as unknown as jest.Mock).mockReturnValue(bot);
  expect(createBot()).toBe(bot); expect(initContent).toHaveBeenCalled();
  expect(bot.use).toHaveBeenCalledWith(websitePairing);
  expect(bot.use.mock.invocationCallOrder[0]).toBeLessThan((registerCommands as jest.Mock).mock.invocationCallOrder[0]);
  expect(registerCommands).toHaveBeenCalledWith(bot); expect(registerCallbacks).toHaveBeenCalledWith(bot); expect(registerAdmin).toHaveBeenCalledWith(bot);
  expect(setTelegramForCommands).toHaveBeenCalledWith(bot.telegram);
  expect(() => bot.catch.mock.calls[0][0](new Error("secret-token"), { update: { message: "secret-code" } })).toThrow("telegram-update-failed");
  const context = {}, next = jest.fn();
  await bot.on.mock.calls[0][1](context, next);
  expect(handleText).toHaveBeenCalledWith(context); expect(next).toHaveBeenCalledTimes(1);
});
